/**
 * Stateful word-pool selector.
 * Prevents repeated words by filtering out recently used words until the pool is exhausted.
 * Synchronized across multiplayer when passed usedWords.
 */
export function getRandomWord(
  category: Category,
  difficulty: Difficulty,
  usedWords?: string[]
): { word: string; category: Category; hint?: string } {
  let selectedCategory = category;
  if (selectedCategory === 'Random') {
    const validCats: Exclude<Category, 'Random'>[] = [
      'Technology',
      'Animals',
      'Movies',
      'Countries',
      'Food',
      'Sports',
      'Medical'
    ];
    selectedCategory = validCats[Math.floor(Math.random() * validCats.length)];
  }

  const fullPool = WORD_DATABASE[selectedCategory as Exclude<Category, 'Random'>][difficulty];

  // If used words are supplied, filter the pool to avoid repeating them
  let eligiblePool = fullPool;
  if (usedWords && usedWords.length > 0) {
    const usedUpper = new Set(usedWords.map((w) => w.toUpperCase().trim()));
    const unselected = fullPool.filter((item) => !usedUpper.has(item.word.toUpperCase().trim()));

    if (unselected.length > 0) {
      eligiblePool = unselected;
    } else {
      // Pool is exhausted! Exclude only the very last word if pool size > 1
      const lastWord = usedWords[usedWords.length - 1]?.toUpperCase().trim();
      const freshFiltered = fullPool.filter((item) => item.word.toUpperCase().trim() !== lastWord);
      eligiblePool = freshFiltered.length > 0 ? freshFiltered : fullPool;
    }
  }

  // Pick random from eligible pool
  const item = eligiblePool[Math.floor(Math.random() * eligiblePool.length)];

  return {
    word: item.word.toUpperCase(),
    category: selectedCategory,
    hint: item.hint
  };
}
